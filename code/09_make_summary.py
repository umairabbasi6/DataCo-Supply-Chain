"""Write RESULTS_SUMMARY.md directly from results/*.csv so the summary can never
drift from the tables.  Run after every other step (run_all.py does this)."""
import glob, os, re
import numpy as np
import pandas as pd
from common import ROOT, RES

def rd(prefix):
    f = [p for p in glob.glob(f"{RES}/{prefix}_*.csv") if "permutation_null" not in p]
    assert len(f) == 1, f"expected exactly one results/{prefix}_*.csv, found {f}"
    return pd.read_csv(f[0]), os.path.basename(f[0])

def pick(df, col, text):
    m = df[df[col].astype(str).str.contains(text, regex=False)]
    assert len(m) == 1, f"'{text}' matched {len(m)} rows in column '{col}'"
    return m.iloc[0]

def md(df):
    df = df.copy()
    for c in df.columns:
        if pd.api.types.is_float_dtype(df[c]):
            df[c] = df[c].map(lambda v: "" if pd.isna(v) else f"{v:.4f}")
    cols = [str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join(str(v).replace("|", "/") for v in r.values) + " |")
    return "\n".join(lines)

A2, _ = rd("A2"); A3, _ = rd("A3"); B3, _ = rd("B3"); B5, _ = rd("B5"); B8, _ = rd("B8")
C2, _ = rd("C2"); C11, _ = rd("C11"); C13, _ = rd("C13"); C5, _ = rd("C5")
c2 = lambda m: pick(C2, "Model", m)["ROC_AUC"]
c11 = lambda t: f"{pick(C11, 'Predictor', t)['ROC-AUC']:.4f}"
def a2(t):
    m = A2[A2["Setting"].astype(str).str.startswith(t)]
    assert len(m) == 1, f"'{t}' matched {len(m)} rows in A2"
    return m.iloc[0]
b5 = lambda t: pick(B5, "Setting", t)["RF ROC-AUC"]
x32 = "x payment Type (32 cells), grouped"
sd = lambda r: f"{r['XGB AUC mean']:.4f} ± {r['XGB AUC SD']:.4f}"

head = f"""# Results Summary (generated by 09_make_summary.py from results/*.csv)

Seed = 42. "Grouped CV" = 5-fold StratifiedGroupKFold by Order Id.
Do not edit by hand: re-run `python 09_make_summary.py`.

## Headline numbers

**DataCo inflation decomposition (XGBoost, A2)**
- Paper single split replicated: {a2('Paper single')['XGB AUC mean']:.4f}
- S0 as submitted (row CV): {sd(a2('S0 '))}
- S1 without Order Status: {sd(a2('S1 '))}
- S2 without shipping date: {sd(a2('S2 '))}
- S3 without order-date string / PII: {sd(a2('S3 '))}
- S4 + grouped CV: {sd(a2('S4 '))}
- S5 clean feature set, grouped CV: {sd(a2('S5 '))}
- Control (+ parsed ship-minus-order days): {sd(a2('Control'))}

**Random forest discrepancy (A3)**
- RF(200, depth 15, balanced), single split: {A3.iloc[0]['AUC']}
- RF(100, unlimited), 5-fold row CV: {A3.iloc[1]['AUC']}
- Same RF(100), grouped CV: {A3.iloc[2]['AUC']}

**IoT audit**
- DS2 permutation test: observed {B3.iloc[0]['Observed AUC']:.4f}, null mean {B3.iloc[0]['Null mean AUC']:.4f} (SD {B3.iloc[0]['Null SD']:.4f}), p = {B3.iloc[0]['Permutation p-value (200 perms)']:.4f}
- Fused RF, single split: {b5('single 80/20'):.4f}; 5-fold: {b5('All 17 features (5-fold CV)'):.4f}
- dataset_source only: {b5('dataset_source flag ONLY'):.4f}; source + speed: {b5('dataset_source + speed'):.4f}
- Within DS2 rows: {b5('within DS2'):.4f}; within DS3 rows: {b5('within DS3'):.4f}
- K-Means vs source file: {pick(B8, 'Metric', 'Adjusted Rand')['Value']:.4f} (ARI); silhouette {pick(B8, 'Metric', 'Silhouette')['Value']:.4f}

**Corrected DataCo benchmark (grouped 5-fold, ROC-AUC mean of folds, C2)**
- XGBoost {c2('XGBoost')}; Random Forest {c2('Random Forest')}; MLP {c2('MLP')}; Logistic Regression {c2('Logistic Regression')}; Shipping Mode only {c2('Shipping Mode only')}

**Lookup table vs ML (pooled out-of-fold ROC-AUC, C11/C13)**
- 4-cell mode lookup, out-of-fold: {c11('Shipping Mode (4 cells), grouped')}
- 8-cell mode x noon lookup, out-of-fold: {c11('(8 cells), grouped')}
- 32-cell lookup in-sample / out-of-fold: {c11('(32 cells), in-sample')} / {c11(x32)}
- XGBoost / Random Forest out-of-fold: {c11('XGBoost, grouped')} / {c11('Random Forest, grouped')}
- Order-level bootstrap, XGBoost minus 32-cell lookup: {C13.iloc[0]['Mean']} (95% CI {C13.iloc[0]['CI 2.5%']} to {C13.iloc[0]['CI 97.5%']})
- Order-level bootstrap, Random Forest minus 32-cell lookup: {C13.iloc[1]['Mean']} (95% CI {C13.iloc[1]['CI 2.5%']} to {C13.iloc[1]['CI 97.5%']})

**Temporal hold-out (C5, ROC-AUC):** """ + "; ".join(
    f"{r['Model']} {r['ROC_AUC']:.4f}" for _, r in C5.iterrows() if "Majority" not in r["Model"]) + """

## Caveats to state in the paper

1. The XGBoost and MLP grids used a 60,000-row sample that overlaps the outer folds;
   they are sensitivity analyses, not nested tuning.
2. DeLong tests treat order items as independent; items of one order share a label,
   so very small p-values are overstated. C13 uses an order-level bootstrap instead.
3. The audit covers three public files only and does not describe IoT logistics data
   in general.

## All tables
"""

TITLE = {}
src = open(os.path.join(ROOT, "code", "06_results_workbook.py"), encoding="utf-8").read()
for k, v in re.findall(r'"([ABC]\d+)":\s*"([^"]+)"', src):
    TITLE[k] = v

def key(p):
    c = os.path.basename(p).split("_")[0]; m = re.match(r"([A-Z])(\d+)", c)
    return (m.group(1), int(m.group(2)))

parts = [head]
for f in sorted((p for p in glob.glob(f"{RES}/*.csv") if "permutation_null" not in p), key=key):
    code = os.path.basename(f).split("_")[0]
    df = pd.read_csv(f)
    if len(df) > 30:
        parts.append(f"### {code}: {TITLE.get(code, '')} (`{os.path.basename(f)}`)\n\n"
                     f"{len(df)} rows; see the CSV / ALL_RESULTS.xlsx.\n")
    else:
        parts.append(f"### {code}: {TITLE.get(code, '')} (`{os.path.basename(f)}`)\n\n{md(df)}\n")
out = os.path.join(ROOT, "RESULTS_SUMMARY.md")
open(out, "w", encoding="utf-8").write("\n".join(parts))
print(f"Saved {out}")
